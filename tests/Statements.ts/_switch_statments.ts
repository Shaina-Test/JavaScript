//in the below example 0 is === 0 so the output is trying to improve
//switch statment should always have a break in the end
//we can have multiple cases inside switch
let marks = 0;
switch(marks){
    case 0: {
        console.log("Trying to improve");
    }
    break;
    case false: {
        console.log("tried my best");
    }
    break;
}