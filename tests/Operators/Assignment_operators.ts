// Assignment Operators
// = += -= *= /= %= **=
let x = 10;
x += 5; // Equivalent to x = x + 5 outputs 15
x -= 3; // Equivalent to x = x - 3 outputs 12
x *= 2; // Equivalent to x = x * 2 outputs 24
x /= 4; // Equivalent to x = x / 4 outputs 6
x %= 3; // Equivalent to x = x % 3 outputs 0
x **= 2; // Equivalent to x = x ** 2 outputs 0